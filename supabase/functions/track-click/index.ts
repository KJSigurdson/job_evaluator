// Click-tracking redirect for the match-digest email.
//
//   GET /functions/v1/track-click?m=<matches_v2.id>&t=<token>
//
// token = first 32 hex chars of HMAC-SHA256(CLICK_LINK_SECRET, matches_v2.id)
// — see src/pipeline_v2.py's _digest_link_url()/_click_token(), which
// generates the exact same value for the link this function validates.
//
// Deliberately never trusts a client-supplied target URL: the only inputs
// are match_id and its token. The redirect destination always comes from a
// server-side lookup (matches_v2.job_id -> jobs.canonical_url), never from
// the request itself.
//
// Verify JWT is OFF for this function by design — a digest-email link is
// clicked with no Supabase auth session at all, so there is no JWT to
// verify. All authorization is instead the HMAC token above (proves the
// link was generated by the pipeline, not guessed/forged) plus this
// function's own service-role DB access.
//
// Event logging (match_events) is best-effort and gated on the MATCHED
// USER's own latest 'behavioral_tracking' consent (fail closed — no row or
// granted=false skips logging) - never on whether this request is
// authenticated, since it never is. The redirect to canonical_url always
// happens once match_id/token validate and the job is found, regardless of
// whether logging succeeds, fails, or is skipped for lack of consent.
//
// No user data in logs beyond match_id, anywhere in this file.
import { createClient } from "npm:@supabase/supabase-js@2";
import { createHmac, timingSafeEqual } from "node:crypto";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
const CLICK_LINK_SECRET = Deno.env.get("CLICK_LINK_SECRET")!;
const APP_URL = Deno.env.get("APP_URL")!;

const CLICK_TOKEN_HEX_LENGTH = 32;
const MATCH_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const client = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);

function expectedToken(matchId: string): string {
  return createHmac("sha256", CLICK_LINK_SECRET)
    .update(matchId)
    .digest("hex")
    .slice(0, CLICK_TOKEN_HEX_LENGTH);
}

function constantTimeEquals(a: string, b: string): boolean {
  // Length is not secret (the token is always CLICK_TOKEN_HEX_LENGTH chars)
  // — comparing it first, before the constant-time body, is safe and lets
  // timingSafeEqual receive only equal-length buffers (it throws otherwise).
  const bufA = new TextEncoder().encode(a);
  const bufB = new TextEncoder().encode(b);
  if (bufA.length !== bufB.length) return false;
  return timingSafeEqual(bufA, bufB);
}

function redirect(url: string): Response {
  return new Response(null, { status: 302, headers: { Location: url } });
}

Deno.serve(async (req: Request) => {
  const url = new URL(req.url);
  const matchId = url.searchParams.get("m");
  const token = url.searchParams.get("t");

  // Basic shape check before touching HMAC/the DB at all — not a security
  // boundary (the HMAC check below is that boundary), just avoids a wasted
  // DB round trip for an obviously malformed link.
  if (!matchId || !token || !MATCH_ID_PATTERN.test(matchId)) {
    return redirect(APP_URL);
  }

  if (!constantTimeEquals(token, expectedToken(matchId))) {
    // Invalid token — redirect with NO logging at all, per this function's
    // explicit contract: a forged/guessed link must leave no trace to
    // probe against (not even at match_id granularity).
    return redirect(APP_URL);
  }

  const { data: match, error: matchError } = await client
    .from("matches_v2")
    .select("user_id, job_id, notified_at")
    .eq("id", matchId)
    .maybeSingle();

  if (matchError || !match) {
    // Valid token, but the match_id itself doesn't exist (or the lookup
    // failed) — a real signal worth logging, unlike a bad token above.
    console.error(`track-click: match lookup failed for match_id=${matchId}`);
    return redirect(APP_URL);
  }

  const { data: job, error: jobError } = await client
    .from("jobs")
    .select("canonical_url")
    .eq("id", match.job_id)
    .maybeSingle();

  if (jobError || !job?.canonical_url) {
    console.error(`track-click: job lookup failed for match_id=${matchId}`);
    return redirect(APP_URL);
  }

  // Best-effort event logging. Never blocks or affects the redirect below —
  // wrapped so that ANY failure here (consent lookup, insert, or an
  // unexpected throw) still reaches the canonical_url redirect.
  try {
    const { data: consentRows } = await client
      .from("user_consents")
      .select("granted, created_at")
      .eq("user_id", match.user_id)
      .eq("consent_key", "behavioral_tracking")
      .order("created_at", { ascending: false })
      .limit(1);

    const latestGranted = consentRows?.[0]?.granted === true;
    if (latestGranted) {
      const secondsSinceSend = match.notified_at
        ? Math.max(0, Math.round((Date.now() - new Date(match.notified_at).getTime()) / 1000))
        : null;
      const { error: insertError } = await client.from("match_events").insert({
        user_id: match.user_id,
        match_id: matchId,
        event_type: "clicked_posting",
        source: "digest",
        details: {
          user_agent: req.headers.get("user-agent"),
          seconds_since_send: secondsSinceSend,
        },
      });
      if (insertError) {
        console.error(`track-click: match_events insert failed for match_id=${matchId}`);
      }
    }
  } catch {
    console.error(`track-click: event logging threw for match_id=${matchId}`);
  }

  return redirect(job.canonical_url);
});
